# Aula: Variáveis e Tipos de Dados em Python
# -------------------------------------------

# 1️- Inteiro (int)
idade = 18
print("Idade:", idade)
print("Tipo de dado:", type(idade))
print()  # linha em branco para separar a saída

# 2️- Número Real / Decimal (float)
altura = 1.75
print("Altura:", altura)
print("Tipo de dado:", type(altura))
print()

# 3️ - Texto (str - string)
nome = "Maria"
print("Nome:", nome)
print("Tipo de dado:", type(nome))
print()

# 4️ - Lógico / Booleano (bool)
maior_de_idade = True
print("Maior de idade:", maior_de_idade)
print("Tipo de dado:", type(maior_de_idade))
print()

# 5️- Exemplo prático combinando os tipos
print("Resumo:")
print(nome, "tem", idade, "anos e mede", altura, "m de altura.")
print("É maior de idade?", maior_de_idade)
